public class LatihanPertama {
    public static void main(String[] args) {

        System.out.println("Nomor Urut Barang Naik:");

        for (int i = 1; i <= 10; i++) {
            System.out.println("Barang ke-" + i);
        }

        System.out.println("\nNomor Urut Barang Turun:");

        for (int i = 10; i >= 1; i--) {
            System.out.println("Barang ke-" + i);
        }
    }
}
